use crate::sql::backend::Backend;
use crate::sql::ir::SchemaIr;

/// Emit Diesel table!, joinable!, and allow_tables_to_appear_in_same_query! declarations.
pub fn emit_diesel_schema<B: Backend>(schema: &SchemaIr, backend: &B) -> String {
    let mut out = String::new();
    out.push_str("//! Auto-generated Diesel table definitions.\n");
    out.push_str("//! @generated by repository::sql\n\n");

    // Tables
    for (table_name, table) in &schema.tables {
        let pk_cols = if let Some(pk) = &table.primary_key {
            pk.columns.join(", ")
        } else {
            "id".to_string()
        };

        out.push_str("diesel::table! {\n");
        out.push_str(&format!("    {table_name} ({pk_cols}) {{\n"));

        for (col_name, col) in &table.columns {
            let sql_type = backend.diesel_sql_type(col, table_name);
            out.push_str(&format!("        {col_name} -> {sql_type},\n"));
        }

        out.push_str("    }\n");
        out.push_str("}\n\n");
    }

    // Joinable! foreign keys
    for (table_name, table) in &schema.tables {
        for fk in &table.foreign_keys {
            let target_table = &fk.target_table;
            if fk.columns.len() == 1 {
                let local_col = &fk.columns[0];
                out.push_str(&format!(
                    "diesel::joinable!({table_name} -> {target_table} ({local_col}));\n"
                ));
            }
        }
    }

    if !schema.tables.is_empty() {
        out.push('\n');
        // allow_tables_to_appear_in_same_query!
        let table_names: Vec<&str> = schema.tables.keys().map(|s| s.as_str()).collect();
        out.push_str("diesel::allow_tables_to_appear_in_same_query!(\n");
        for (i, name) in table_names.iter().enumerate() {
            if i + 1 == table_names.len() {
                out.push_str(&format!("    {name}\n"));
            } else {
                out.push_str(&format!("    {name},\n"));
            }
        }
        out.push_str(");\n");
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sql::backend::SqliteBackend;
    use crate::sql::ir::*;
    use std::collections::BTreeMap;

    #[test]
    fn test_emit_diesel_schema() {
        let mut tables = BTreeMap::new();
        let mut users_cols = BTreeMap::new();
        let mut id_col = ColumnIr::new(ColumnType::Integer);
        id_col.auto_increment = true;
        users_cols.insert("id".to_string(), id_col);

        let name_col = ColumnIr::new(ColumnType::Text);
        users_cols.insert("name".to_string(), name_col);

        tables.insert(
            "users".to_string(),
            TableIr {
                columns: users_cols,
                primary_key: Some(PrimaryKeyIr {
                    columns: vec!["id".to_string()],
                    name: None,
                }),
                foreign_keys: Vec::new(),
                unique_constraints: Vec::new(),
                indexes: Vec::new(),
                check_constraints: Vec::new(),
                renamed_from: None,
                rust_name: None,
            },
        );

        let mut posts_cols = BTreeMap::new();
        let mut post_id_col = ColumnIr::new(ColumnType::Integer);
        post_id_col.auto_increment = true;
        posts_cols.insert("id".to_string(), post_id_col);

        let author_col = ColumnIr::new(ColumnType::Integer);
        posts_cols.insert("author_id".to_string(), author_col);

        tables.insert(
            "posts".to_string(),
            TableIr {
                columns: posts_cols,
                primary_key: Some(PrimaryKeyIr {
                    columns: vec!["id".to_string()],
                    name: None,
                }),
                foreign_keys: vec![ForeignKeyIr {
                    columns: vec!["author_id".to_string()],
                    target_table: "users".to_string(),
                    target_columns: vec!["id".to_string()],
                    on_delete: ReferentialAction::Cascade,
                    on_update: ReferentialAction::Cascade,
                    name: None,
                }],
                unique_constraints: Vec::new(),
                indexes: Vec::new(),
                check_constraints: Vec::new(),
                renamed_from: None,
                rust_name: None,
            },
        );

        let schema = SchemaIr {
            ir_version: 1,
            naming: NamingConfig::default(),
            enums: BTreeMap::new(),
            tables,
        };

        let dsl = emit_diesel_schema(&schema, &SqliteBackend);
        assert!(dsl.contains("diesel::table! {"));
        assert!(dsl.contains("users (id) {"));
        assert!(dsl.contains("diesel::joinable!(posts -> users (author_id));"));
        assert!(dsl.contains("diesel::allow_tables_to_appear_in_same_query!("));
    }
}
