use crate::sql::ir::SchemaIr;
use crate::sql::naming::{resolve_field_name, resolve_new_struct_name, resolve_struct_name};

/// Emit typed table repository classes and database entrypoint (e.g. `db.users.create(...)`).
pub fn emit_repositories(schema: &SchemaIr) -> String {
    let mut out = String::new();
    out.push_str("//! Auto-generated typed repositories and query executors.\n");
    out.push_str("//! @generated by repository::sql\n\n");
    out.push_str("use crate::sql::runtime::{Exec, DbError};\n\n");

    for (table_name, table) in &schema.tables {
        let struct_name = resolve_struct_name(table_name, table.rust_name.as_deref());
        let new_struct_name = resolve_new_struct_name(table_name, table.rust_name.as_deref());
        let repo_name = format!("{struct_name}Repository");

        out.push_str(&format!("/// Typed repository for `{table_name}` table operations.\n"));
        out.push_str(&format!("#[derive(Clone)]\npub struct {repo_name} {{\n    pub(crate) exec: Exec,\n}}\n\n"));

        out.push_str(&format!("impl {repo_name} {{\n"));
        out.push_str("    pub fn new(exec: Exec) -> Self {\n        Self { exec }\n    }\n\n");

        // Insert
        out.push_str(&format!(
            "    /// Insert a record into `{table_name}`.\n"
        ));
        out.push_str(&format!(
            "    pub fn create(&self, data: {new_struct_name}) -> Result<{struct_name}, DbError> {{\n"
        ));
        out.push_str("        self.exec.run(move |conn| {\n");
        out.push_str("            use diesel::RunQueryDsl;\n");
        out.push_str(&format!(
            "            diesel::insert_into(crate::schema::{table_name}::table)\n"
        ));
        out.push_str("                .values(&data)\n");
        out.push_str("                .get_result(conn)\n");
        out.push_str("                .map_err(DbError::from_diesel)\n");
        out.push_str("        })\n");
        out.push_str("    }\n\n");

        // Find by primary key (if single PK)
        if let Some(pk) = &table.primary_key {
            if pk.columns.len() == 1 {
                let pk_col_name = &pk.columns[0];
                let pk_field = resolve_field_name(pk_col_name, None);
                let pk_type = if let Some(col) = table.columns.get(pk_col_name) {
                    if col.r#type.is_integer() { "i32" } else { "String" }
                } else {
                    "i32"
                };

                out.push_str(&format!(
                    "    /// Find a record in `{table_name}` by primary key `{pk_col_name}`.\n"
                ));
                out.push_str(&format!(
                    "    pub fn find_by_pk(&self, {pk_field}: {pk_type}) -> Result<Option<{struct_name}>, DbError> {{\n"
                ));
                out.push_str("        self.exec.run(move |conn| {\n");
                out.push_str("            use diesel::QueryDsl;\n");
                out.push_str("            use diesel::RunQueryDsl;\n");
                out.push_str(&format!(
                    "            crate::schema::{table_name}::table\n"
                ));
                out.push_str(&format!(
                    "                .find({pk_field})\n"
                ));
                out.push_str("                .first(conn)\n");
                out.push_str("                .map(Some)\n");
                out.push_str("                .or_else(|e| if e == diesel::result::Error::NotFound { Ok(None) } else { Err(DbError::from_diesel(e)) })\n");
                out.push_str("        })\n");
                out.push_str("    }\n\n");

                out.push_str(&format!(
                    "    /// Delete a record in `{table_name}` by primary key `{pk_col_name}`.\n"
                ));
                out.push_str(&format!(
                    "    pub fn delete_by_pk(&self, {pk_field}: {pk_type}) -> Result<usize, DbError> {{\n"
                ));
                out.push_str("        self.exec.run(move |conn| {\n");
                out.push_str("            use diesel::QueryDsl;\n");
                out.push_str("            use diesel::RunQueryDsl;\n");
                out.push_str(&format!(
                    "            diesel::delete(crate::schema::{table_name}::table.find({pk_field}))\n"
                ));
                out.push_str("                .execute(conn)\n");
                out.push_str("                .map_err(DbError::from_diesel)\n");
                out.push_str("        })\n");
                out.push_str("    }\n\n");
            }
        }

        // List / find_all
        out.push_str(&format!(
            "    /// Query all records in `{table_name}`.\n"
        ));
        out.push_str(&format!(
            "    pub fn find_all(&self) -> Result<Vec<{struct_name}>, DbError> {{\n"
        ));
        out.push_str("        self.exec.run(move |conn| {\n");
        out.push_str("            use diesel::RunQueryDsl;\n");
        out.push_str(&format!(
            "            crate::schema::{table_name}::table.load(conn).map_err(DbError::from_diesel)\n"
        ));
        out.push_str("        })\n");
        out.push_str("    }\n");

        out.push_str("}\n\n");
    }

    // Top-level Database client class
    out.push_str("/// Top-level database access client exposing typed repositories.\n");
    out.push_str("#[derive(Clone)]\npub struct Database {\n    pub(crate) exec: Exec,\n");
    for (table_name, table) in &schema.tables {
        let struct_name = resolve_struct_name(table_name, table.rust_name.as_deref());
        let repo_name = format!("{struct_name}Repository");
        out.push_str(&format!("    pub {table_name}: {repo_name},\n"));
    }
    out.push_str("}\n\n");

    out.push_str("impl Database {\n");
    out.push_str("    pub fn new(exec: Exec) -> Self {\n");
    out.push_str("        Self {\n");
    for table_name in schema.tables.keys() {
        let struct_name = resolve_struct_name(table_name, None);
        let repo_name = format!("{struct_name}Repository");
        out.push_str(&format!("            {table_name}: {repo_name}::new(exec.clone()),\n"));
    }
    out.push_str("            exec,\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n");

    out
}
