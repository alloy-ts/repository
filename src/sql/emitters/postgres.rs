use crate::sql::backend::Backend;
use crate::sql::ir::SchemaIr;
use crate::sql::naming::resolve_enum_type_name;

/// Emit Postgres SQL types module declarations for custom enums (`sql_types::<EnumName>`).
pub fn emit_postgres_sql_types(schema: &SchemaIr) -> String {
    let mut out = String::new();
    out.push_str("//! Auto-generated PostgreSQL Diesel SQL types for enums.\n");
    out.push_str("//! @generated by repository::sql\n\n");
    out.push_str("pub mod sql_types {\n");

    for (enum_name, enum_def) in &schema.enums {
        let rust_name = resolve_enum_type_name(enum_name, enum_def.rust_name.as_deref());
        out.push_str("    #[derive(diesel::sql_types::SqlType)]\n");
        out.push_str(&format!(
            "    #[diesel(postgres_type(name = \"{enum_name}\"))]\n"
        ));
        out.push_str(&format!("    pub struct {rust_name};\n\n"));
    }

    out.push_str("}\n");
    out
}

/// Emit Postgres-specific diesel `schema.rs` declarations.
pub fn emit_postgres_diesel_schema(schema: &SchemaIr) -> String {
    let mut out = String::new();
    out.push_str("//! Auto-generated Diesel PostgreSQL table definitions.\n");
    out.push_str("//! @generated by repository::sql\n\n");

    let postgres = crate::sql::backend::PostgresBackend;

    // First emit sql_types module if any enums exist
    if !schema.enums.is_empty() {
        out.push_str(&emit_postgres_sql_types(schema));
        out.push('\n');
    }

    // Tables
    for (table_name, table) in &schema.tables {
        let pk_cols = if let Some(pk) = &table.primary_key {
            pk.columns.join(", ")
        } else {
            "id".to_string()
        };

        out.push_str("diesel::table! {\n");
        if !schema.enums.is_empty() {
            out.push_str("    use diesel::sql_types::*;\n");
            out.push_str("    use super::sql_types::*;\n\n");
        }
        out.push_str(&format!("    {table_name} ({pk_cols}) {{\n"));

        for (col_name, col) in &table.columns {
            let sql_type = postgres.diesel_sql_type(col, table_name);
            out.push_str(&format!("        {col_name} -> {sql_type},\n"));
        }

        out.push_str("    }\n");
        out.push_str("}\n\n");
    }

    // Joinable! foreign keys
    for (table_name, table) in &schema.tables {
        for fk in &table.foreign_keys {
            let target_table = &fk.target_table;
            if fk.columns.len() == 1 {
                let local_col = &fk.columns[0];
                out.push_str(&format!(
                    "diesel::joinable!({table_name} -> {target_table} ({local_col}));\n"
                ));
            }
        }
    }

    if !schema.tables.is_empty() {
        out.push('\n');
        let table_names: Vec<&str> = schema.tables.keys().map(|s| s.as_str()).collect();
        out.push_str("diesel::allow_tables_to_appear_in_same_query!(\n");
        for (i, name) in table_names.iter().enumerate() {
            if i + 1 == table_names.len() {
                out.push_str(&format!("    {name}\n"));
            } else {
                out.push_str(&format!("    {name},\n"));
            }
        }
        out.push_str(");\n");
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sql::ir::*;
    use std::collections::BTreeMap;

    #[test]
    fn test_emit_postgres_sql_types() {
        let mut enums = BTreeMap::new();
        enums.insert(
            "user_role".to_string(),
            EnumIr {
                values: vec!["admin".to_string(), "viewer".to_string()],
                rust_name: None,
            },
        );

        let schema = SchemaIr {
            ir_version: 1,
            naming: NamingConfig::default(),
            enums,
            tables: BTreeMap::new(),
        };

        let out = emit_postgres_sql_types(&schema);
        assert!(out.contains("pub mod sql_types {"));
        assert!(out.contains("#[diesel(postgres_type(name = \"user_role\"))]"));
        assert!(out.contains("pub struct UserRole;"));
    }

    #[test]
    fn test_emit_postgres_diesel_schema() {
        let mut tables = BTreeMap::new();
        let mut users_cols = BTreeMap::new();
        let mut id_col = ColumnIr::new(ColumnType::Integer);
        id_col.auto_increment = true;
        users_cols.insert("id".to_string(), id_col);

        let mut role_col = ColumnIr::new(ColumnType::Enum {
            name: "user_role".to_string(),
        });
        users_cols.insert("role".to_string(), role_col);

        tables.insert(
            "users".to_string(),
            TableIr {
                columns: users_cols,
                primary_key: Some(PrimaryKeyIr {
                    columns: vec!["id".to_string()],
                    name: None,
                }),
                foreign_keys: Vec::new(),
                unique_constraints: Vec::new(),
                indexes: Vec::new(),
                check_constraints: Vec::new(),
                renamed_from: None,
                rust_name: None,
            },
        );

        let mut enums = BTreeMap::new();
        enums.insert(
            "user_role".to_string(),
            EnumIr {
                values: vec!["admin".to_string(), "viewer".to_string()],
                rust_name: None,
            },
        );

        let schema = SchemaIr {
            ir_version: 1,
            naming: NamingConfig::default(),
            enums,
            tables,
        };

        let out = emit_postgres_diesel_schema(&schema);
        assert!(out.contains("pub mod sql_types"));
        assert!(out.contains("users (id) {"));
        assert!(out.contains("role -> crate::sql_types::UserRole"));
    }
}
