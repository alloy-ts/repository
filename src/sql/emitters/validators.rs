use crate::sql::ir::{ColumnType, SchemaIr};
use crate::sql::naming::{resolve_field_name, resolve_struct_name};

/// Emit runtime `validate(&self) -> Result<(), Vec<String>>` methods for generated Row structs.
pub fn emit_validators(schema: &SchemaIr) -> String {
    let mut out = String::new();
    out.push_str("//! Auto-generated runtime model validators.\n");
    out.push_str("//! @generated by repository::sql\n\n");

    for (table_name, table) in &schema.tables {
        let struct_name = resolve_struct_name(table_name, table.rust_name.as_deref());

        out.push_str(&format!("impl {struct_name} {{\n"));
        out.push_str("    /// Validate runtime field constraints (e.g. maxLength).\n");
        out.push_str("    pub fn validate(&self) -> Result<(), Vec<String>> {\n");
        out.push_str("        let mut errors = Vec::new();\n\n");

        for (col_name, col) in &table.columns {
            let field_name = resolve_field_name(col_name, col.rust_name.as_deref());

            if let Some(max_len) = col.max_length {
                if matches!(col.r#type, ColumnType::Text) {
                    if col.nullable {
                        out.push_str(&format!(
                            "        if let Some(ref val) = self.{field_name} {{\n"
                        ));
                        out.push_str(&format!(
                            "            if val.len() > {max_len} {{\n"
                        ));
                        out.push_str(&format!(
                            "                errors.push(format!(\"field '{field_name}' length {{}} exceeds max {max_len}\", val.len()));\n"
                        ));
                        out.push_str("            }\n");
                        out.push_str("        }\n");
                    } else {
                        out.push_str(&format!(
                            "        if self.{field_name}.len() > {max_len} {{\n"
                        ));
                        out.push_str(&format!(
                            "            errors.push(format!(\"field '{field_name}' length {{}} exceeds max {max_len}\", self.{field_name}.len()));\n"
                        ));
                        out.push_str("        }\n");
                    }
                }
            }
        }

        out.push_str("\n        if errors.is_empty() {\n");
        out.push_str("            Ok(())\n");
        out.push_str("        } else {\n");
        out.push_str("            Err(errors)\n");
        out.push_str("        }\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sql::ir::*;
    use std::collections::BTreeMap;

    #[test]
    fn test_emit_validators() {
        let mut tables = BTreeMap::new();
        let mut users_cols = BTreeMap::new();
        users_cols.insert(
            "name".to_string(),
            ColumnIr {
                r#type: ColumnType::Text,
                nullable: false,
                auto_increment: false,
                max_length: Some(50),
                default: None,
                renamed_from: None,
                rust_name: None,
            },
        );

        tables.insert(
            "users".to_string(),
            TableIr {
                columns: users_cols,
                primary_key: None,
                foreign_keys: Vec::new(),
                unique_constraints: Vec::new(),
                indexes: Vec::new(),
                check_constraints: Vec::new(),
                renamed_from: None,
                rust_name: None,
            },
        );

        let schema = SchemaIr {
            ir_version: 1,
            naming: NamingConfig::default(),
            enums: BTreeMap::new(),
            tables,
        };

        let generated = emit_validators(&schema);
        assert!(generated.contains("impl User {"));
        assert!(generated.contains("pub fn validate(&self) -> Result<(), Vec<String>>"));
        assert!(generated.contains("if self.name.len() > 50"));
    }
}
